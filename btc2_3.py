def E15_PCA_dim(x):
    try:
        X = build_ps(x, emb=10)
        if X is None: return np.nan
        pca = PCA().fit(X)
        cumvar = np.cumsum(pca.explained_variance_ratio_)
        return float(np.searchsorted(cumvar, 0.95) + 1)
    except: return np.nan

