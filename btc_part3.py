    w='Seuil' if label.startswith('T7') else 'M7>'
    print(f"  {w:>7}  {'PF_IS':>7}  {'PF_OOS':>8}  {'N_OOS':>7}  {'P_OOS':>8}  Verdict")
    print("  "+"─"*58)
    for s in seuils:
        t_oos=np.concatenate([backtest(BTC[m]['long'],BTC[m]['short'],
                              signal_fn_oos(m,s),BTC[m]['prix'])
                              for m in mois_oos if m in BTC])
